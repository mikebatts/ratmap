import { chromium, devices } from "playwright";
const b = await chromium.launch();
const ctx = await b.newContext({ ...devices["iPhone 13"], colorScheme: "dark" });
const p = await ctx.newPage();
const errs = [];
p.on("pageerror", (e) => errs.push("PAGEERR " + e.message));
p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
await p.goto("http://localhost:3000/", { waitUntil: "networkidle", timeout: 30000 });
await p.waitForTimeout(4000);
const s = p.getByPlaceholder(/Search an address/i);
await s.click(); await s.fill("350 5th ave");
await p.waitForTimeout(1300);
await p.locator("ul[role=listbox] li button").first().click();
await p.waitForTimeout(3500);
const detail = await p.getByRole("dialog").first().isVisible().catch(()=>false);
const searchBarVisible = await s.isVisible().catch(()=>false);
await p.screenshot({ path: "scripts/m-detail.png" });
console.log(`detailSheet=${detail} searchBarHiddenWhileDetailOpen=${!searchBarVisible} errors=${errs.length?errs.join(" | "):"(none)"}`);
await b.close();
